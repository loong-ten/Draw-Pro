import assert from 'node:assert/strict';
import { bounds, exportBounds, layoutLayers, alignLayers, snapTranslation, hitLayer } from '../dist/composition-geometry.js';
const make = (extra = {}) => ({ id: 'a', x: 0, y: 0, w: 100, h: 80, rotation: 0, visible: true, locked: false, ...extra });
const near = (actual, expected, message) => assert.ok(Math.abs(actual - expected) < 1e-8, message + ': ' + actual);
const negative = exportBounds([make({x:-20,y:-10}),make({id:'b',x:100,y:50,w:60,h:40})]);
assert.deepEqual(negative,{x:-20,y:-10,right:160,bottom:90,w:180,h:100});
const rotated = exportBounds([make({w:450,h:600,rotation:90})]);
assert.equal(rotated.w,600); assert.equal(rotated.h,450);
const diagonal = bounds([make({w:100,h:100,rotation:45})]);
near(diagonal.w,Math.SQRT2*100,'45 degree bounds');
const original = [make(),make({id:'b',w:60,h:40})];
const arranged = layoutLayers(original,{mode:'row',gap:24,normalize:true});
assert.deepEqual(exportBounds(arranged),{x:0,y:0,right:244,bottom:80,w:244,h:80});
assert.equal(original[1].w,60,'layout never mutates source');
const grid = layoutLayers([make(),make({id:'b',w:50,h:40}),make({id:'c',w:30,h:70})],{mode:'grid',gap:10,columns:2});
assert.equal(grid[1].x,110); assert.equal(grid[2].y,90);
const aligned = alignLayers([make({rotation:45}),make({id:'b',x:200,y:180,w:50,h:40})],'left');
near(bounds([aligned[0]]).x,bounds([aligned[1]]).x,'rotated left alignment');
const snap = snapTranslation([make({x:102})],[make({id:'b',x:0})],7);
assert.equal(snap.dx,-2);
const guideSnap = snapTranslation([make({x:103})],[],7,[{type:'v',x:100,y:0}]);
assert.equal(guideSnap.dx,-3); assert.equal(guideSnap.dy,0);
assert.equal(hitLayer([make({rotation:90})],{x:50,y:40})?.id,'a');
assert.equal(hitLayer([make({locked:true})],{x:50,y:40}),null);
console.log('Composition geometry: 10 scenarios passed (negative origin, rotation, boundaries, layouts, alignment, source immutability, image/reference snapping and hit testing).');
